test('@cover editing persists and legacy cover opens', async ({ page }) => {
  await makeDemo(page)
  const editor = page.locator('.result-info .cover-editor')
  await expect(editor.locator('canvas')).toBeVisible()
  if (test.info().project.name === 'desktop') {
    const drag = editor.locator('.cover-drag')
    await drag.hover()
    const box = await drag.boundingBox()
    expect(box).not.toBeNull()
    await page.mouse.down()
    await page.mouse.move(box!.x + box!.width / 2 + 45, box!.y + box!.height / 2, { steps: 4 })
    await expect(editor.getByLabel('По горизонтали')).not.toHaveValue('0')
    await drag.dispatchEvent('pointercancel', { pointerId: 1 })
    await expect(editor.getByLabel('По горизонтали')).toHaveValue('0')
    await page.mouse.up()
  }
  await editor.getByRole('button', { name: 'Заполнить' }).click()
  await editor.getByLabel('Масштаб').fill('1.32')
  await editor.getByLabel('По горизонтали').fill('0.4')
  await editor.getByLabel('Фильтр').selectOption('mono')
  await expect.poll(() => editor.locator('canvas').evaluate(canvas => (canvas as HTMLCanvasElement).width)).toBe(600)
  await expect.poll(() => editor.locator('canvas').evaluate(canvas => {
    const pixel = (canvas as HTMLCanvasElement).getContext('2d')!.getImageData(300, 300, 1, 1).data
    return Math.abs(pixel[0] - pixel[1]) + Math.abs(pixel[1] - pixel[2])
  })).toBeLessThan(8)
  const preview = await editor.locator('canvas').evaluate(canvas => {
    const context = (canvas as HTMLCanvasElement).getContext('2d')!
    return [[20, 20], [300, 300], [300, 500]].map(([x, y]) => Array.from(context.getImageData(x, y, 1, 1).data))
  })
  await page.getByRole('button', { name: 'Сохранить пластинку' }).click()
  await expect(page.getByRole('button', { name: 'Сохранено' })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать обложку' }).click()
  const file = await download
  const { readFile } = await import('node:fs/promises')
  const bytes = await readFile(await file.path())
  expect(bytes.subarray(0, 8).toString('hex')).toBe('89504e470d0a1a0a')
  expect(bytes.readUInt32BE(16)).toBe(1200)
  const exported = await page.evaluate(async encoded => {
    const image = new Image()
    image.src = `data:image/png;base64,${encoded}`
    await image.decode()
    const canvas = document.createElement('canvas')
    canvas.width = canvas.height = 600
    const context = canvas.getContext('2d')!
    context.drawImage(image, 0, 0, 600, 600)
    return [[20, 20], [300, 300], [300, 500]].map(([x, y]) => Array.from(context.getImageData(x, y, 1, 1).data))
  }, bytes.toString('base64'))
  exported.forEach((pixel, index) => pixel.forEach((channel, offset) => expect(Math.abs(channel - preview[index][offset])).toBeLessThan(20)))
  await page.goto('/collection')
  await page.getByRole('link', { name: /Рыжик:/ }).click()
  const detail = page.locator('.detail-grid .cover-editor')
  await expect(detail.getByRole('button', { name: 'Заполнить' })).toHaveClass(/active/)
  await expect(detail.getByLabel('Фильтр')).toHaveValue('mono')
  await expect(detail.getByLabel('По горизонтали')).toHaveValue('0.4')
  await page.evaluate(async () => {
    const request = indexedDB.open('meowax')
    const db = await new Promise<IDBDatabase>((resolve, reject) => { request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    const transaction = db.transaction('albums', 'readwrite')
    const store = transaction.objectStore('albums')
    const all = store.getAll()
    await new Promise<void>((resolve, reject) => { all.onsuccess = () => { const album = all.result[0]; delete album.cover; store.put(album); resolve() }; all.onerror = () => reject(all.error) })
    await new Promise<void>((resolve, reject) => { transaction.oncomplete = () => resolve(); transaction.onerror = () => reject(transaction.error) })
    db.close()
  })
  await page.reload()
  await expect(page.locator('.detail-grid .cover-editor').getByRole('button', { name: 'Вписать' })).toHaveClass(/active/)
})

test('@player play pause stop, noise and needle', async ({ page }) => {
  await makeDemo(page)
  const player = page.locator('.result-grid .player-card')
  await player.getByRole('button', { name: 'Воспроизвести' }).click()
  await expect(player.getByRole('button', { name: 'Пауза' })).toBeVisible()
  await player.getByRole('button', { name: 'Пауза' }).click()
  await expect(player.getByRole('button', { name: 'Воспроизвести' })).toBeVisible()
  await player.getByRole('button', { name: 'Остановить' }).click()
  await expect(player.locator('.turntable')).toHaveAttribute('data-playing', 'false')
  await player.getByLabel('Шум винила').uncheck()
  await page.goto('/settings')
  await expect(page.getByLabel('Шум винила')).not.toBeChecked()
  await page.goto('/')
  await page.getByRole('button', { name: 'Примеры' }).click()
  await page.getByRole('button', { name: 'Рыжик' }).click()
  await page.getByRole('button', { name: 'Распознать котика' }).click()
  const arm = page.getByRole('button', { name: /Тонарм:/ })
  await arm.scrollIntoViewIfNeeded()
  const box = await arm.boundingBox()
  expect(box).not.toBeNull()
  if (test.info().project.name === 'mobile') {
    const cdp = await page.context().newCDPSession(page)
    const x = box!.x + box!.width / 2, y = box!.y + box!.height / 2
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y, id: 1 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y + 90, id: 1 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await cdp.detach()
  } else {
    await arm.hover()
    await page.mouse.down()
    await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2 + 90, { steps: 5 })
    await page.mouse.up()
  }
  await expect(page.getByRole('button', { name: 'Пауза' })).toBeVisible()
  await page.getByRole('button', { name: 'Остановить' }).click()
  await page.getByRole('button', { name: 'Другой трек' }).click()
  await page.getByRole('button', { name: 'Воспроизвести' }).click()
  await expect(page.getByRole('button', { name: 'Пауза' })).toBeVisible()
  await page.goto('/about')
  await expect(page.getByRole('heading', { name: 'Коты. Музыка. Немного магии.' })).toBeVisible()
})

test('@a11y keyboard needle and reduced motion', async ({ page }) => {
  await makeDemo(page)
  await expect(page.getByRole('status')).toBeAttached()
  const arm = page.getByRole('button', { name: /Тонарм:/ })
  await arm.focus()
  await expect(arm).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: 'Пауза' })).toBeVisible()
  await page.goto('/settings')
  await page.getByLabel('Уменьшить анимацию').check()
  await expect(page.locator('html')).toHaveAttribute('data-reduce-motion', 'true')
  await page.goto('/')
  await page.getByRole('button', { name: 'Примеры' }).click()
  await page.getByRole('button', { name: 'Рыжик' }).click()
  await page.getByRole('button', { name: 'Распознать котика' }).click()
  await page.getByRole('button', { name: 'Сохранить пластинку' }).click()
  await page.goto('/collection')
  await page.getByRole('button', { name: 'Удалить Рыжик' }).click()
  const dialog = page.getByRole('dialog', { name: 'Удалить эту пластинку?' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Отмена' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
})
